def _resolve_preset_protein(args) -> Optional[str]:
    """Resolve any CLI-supplied protein sequence, or return None for interactive."""
    if args.protein and args.protein_file:
        raise SystemExit("[args] specify either --protein or --protein-file, not both.")
    if args.protein:
        seq = _read_protein_input(args.protein)
        print("="*72)
        print(" [CLI] protein sequence received via --protein")
        _echo_input_fingerprint(seq, label="cli-protein")
        print("="*72)
        return seq
    if args.protein_file:
        path = Path(args.protein_file).expanduser().resolve()
        if not path.exists():
            raise SystemExit(f"[args] --protein-file not found: {path}")
        # Read first non-empty line; ignore FASTA headers if present.
        lines = [l.strip() for l in path.read_text().splitlines() if l.strip()]
        if lines and lines[0].startswith(">"):
            lines = lines[1:]
        seq = _read_protein_input("".join(lines))
        print("="*72)
        print(f" [CLI] protein sequence loaded from {path}")
        _echo_input_fingerprint(seq, label="file-protein")
        print("="*72)
        return seq
    return None


def main():
    args = _parse_args()

    random.seed(SEED)
    np.random.seed(SEED)
    torch.manual_seed(SEED)
    # Determinism flags — make generation reproducible across runs.
    try:
        torch.backends.cudnn.deterministic = True
        torch.backends.cudnn.benchmark = False
    except Exception:
        pass
    try:
        torch.use_deterministic_algorithms(True, warn_only=True)
    except Exception:
        pass

    print("=" * 72)
    print(" GENERATIVE DRUG DISCOVERY (Seq2Seq Transformer + Rule-Driven)")
    print(" + AUTO-RUN VALIDATION PIPELINE (merged from tryoutDrugs.py)")
    print("=" * 72)
    print(f" Learning rule:  Δw = {RULE_EXPR}")
    print("=" * 72)

    device = pick_device()
    items = download_dataset()
    X, Y, prot_vocab, self_vocab = build_dataset(items)

    ckpt_path = CKPT_DIR / "drug_gpt.pth"
    do_load = False
    if ckpt_path.exists() and not args.retrain:
        if args.load_only:
            do_load = True
        else:
            print(f"\n[checkpoint] Found existing model at {ckpt_path}.")
            choice = input("Do you want to (1) Retrain or (2) Load existing and generate? [1/2]: ").strip()
            do_load = (choice == '2')

    if do_load:
        ckpt = torch.load(ckpt_path, map_location=device, weights_only=False)
        prot_vocab.word2idx = ckpt["prot_vocab"]
        self_vocab.word2idx = ckpt["self_vocab"]
        prot_vocab.idx2word = {v: k for k, v in prot_vocab.word2idx.items()}
        self_vocab.idx2word = {v: k for k, v in self_vocab.word2idx.items()}

        model = DrugDiscoveryTransformer(
            prot_vocab_size=len(prot_vocab),
            self_vocab_size=len(self_vocab)
        ).to(device)
        model.load_state_dict(ckpt["model_state_dict"])

        if "rule" in ckpt:
            print(f"[checkpoint] was trained with rule: Δw = {ckpt['rule']}")
        # ===== load-only path: generate, then auto-run full validation =====
        preset = _resolve_preset_protein(args)
        predict_interactive(model, prot_vocab, self_vocab, device,
                            preset_protein=preset)
        return

    model = train_model(X, Y, prot_vocab, self_vocab, device,
                        epochs=DEFAULT_EPOCHS,
                        batch_size=DEFAULT_BATCH_SIZE,
                        lr=DEFAULT_LR,
                        save_path=ckpt_path)
    preset = _resolve_preset_protein(args)
    predict_interactive(model, prot_vocab, self_vocab, device,
                        preset_protein=preset)

if __name__ == "__main__":
    main()
