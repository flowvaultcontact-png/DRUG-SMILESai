def run_full_validation_pipeline(selfies_str: str, protein_seq: str,
                                 expected_smiles: Optional[str] = None) -> Optional[Dict]:
    """Run every check from tryoutDrugs.py against the generated remedy.

    Parameters
    ----------
    selfies_str     : the SELFIES string produced by the loaded model
    protein_seq     : the input amino-acid sequence used for generation
    expected_smiles : optional canonical SMILES (defaults to the decoded one)

    Returns
    -------
    dict | None     : aggregated validation results, or None if molecule invalid
    """
    print("\n" + "#"*70)
    print("# GENERATED REMEDY — FULL VALIDATION PIPELINE (auto-run)")
    print("#"*70)
    print(f"   Protein length          : {len(protein_seq)} AAs")
    print(f"   SELFIES length          : {len(selfies_str)} chars")

    mol = rdkit_validation(selfies_str, expected_smiles)
    if mol is None:
        print("   Molecule invalid — aborting validation pipeline.")
        return None

    pc      = physchem_profile(mol)
    sa      = synthetic_accessibility(mol)
    filters = druglikeness_filters(mol, pc)
    tox     = toxicity_screen(mol)
    sol     = solubility_estimate(mol, pc)
    admet   = admet_quick(mol, pc)

    # Use the canonical SMILES for any downstream web/API calls.
    smiles_for_calls = expected_smiles or Chem.MolToSmiles(mol)
