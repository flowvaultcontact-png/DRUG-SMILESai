    print(f"   Plasma protein bind : {ppb}")
    print(f"   Metabolic stability : {'possibly low (ester/amide)' if amide_alert else 'moderate'}")
    return dict(oral=oral_absorption, bbb=bbb, cyp=cyp_risk, ppb=ppb)


