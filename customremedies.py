def _read_protein_input(seq: str) -> str:
    """Normalize a pasted protein sequence: strip whitespace, uppercase, keep AAs only."""
    seq = re.sub(r"\s+", "", seq).upper()
    # keep only the 20 standard AAs; anything else is dropped with a warning
    aa_set = set("ACDEFGHIKLMNPQRSTVWY")
    filtered = "".join(c for c in seq if c in aa_set)
    if filtered != seq:
        print(f"  [input] dropped {len(seq) - len(filtered)} non-AA characters")
    return filtered


def _echo_input_fingerprint(seq: str, label: str = "received") -> None:
    """Print length + SHA1 of the input so two runs can be compared side-by-side.
    This is the single most important sanity check: if two runs report different
    lengths or different SHA1s, you are feeding different inputs to the model,
    and you will get different SELFIES / QED — even with the same checkpoint."""
    sha1 = hashlib.sha1(seq.encode("utf-8")).hexdigest()[:16]
    head = seq[:20] + ("..." if len(seq) > 20 else "")
    tail = ("..." if len(seq) > 20 else "") + seq[-20:]
    print(f"  [input] {label}: length={len(seq)} AA | SHA1={sha1}")
    print(f"  [input] head={head}")
    print(f"  [input] tail={tail}")


