    binding_pocket(pdb)
    molecular_docking(smiles_for_calls, pdb or "receptor.pdb")
    md_simulation(pdb)
    free_energy_calc()
    selectivity_analysis()
    experimental_validation_checklist()
    aggregate_verdict(pc, tox, sol, admet, sa)

    return dict(physchem=pc, sa=sa, filters=filters, tox=tox,
                sol=sol, admet=admet, pdb=pdb)

